#!/usr/bin/env python3
"""One-time bootstrap of the local GitLab: users, tokens, group, project, glab auth.

Idempotent and state-deriving — safe to run repeatedly. Verified against GitLab 19.2.1.

Two deliberate design choices, both learned the hard way:

* **Only the root token is minted via `gitlab-rails`.** A rails runner boots a second
  full Rails app (~1.5 GB); in a 6 GB VM that OOM-kills the whole VM (taking the docker
  daemon with it), so puma+sidekiq are stopped for the duration. Everything else goes
  through the REST API.
* **Users are created via the API, never via `User.new(...).save!` in rails** — that
  bypasses personal-namespace creation and fails with "Namespace can't be blank".
  The API uses GitLab's own service and gets it right.

Run `docker compose up -d` first, then:  python3 bootstrap.py

Fixture data (branches, MRs, threads) is NOT created here — that is fixture.py.
"""
